/*  safeMarkdownParse：Markdown 渲染异常时的纯文本兜底                */
/* ─────────────────────────────────────────────────────────────────── */
/*  本文件原先还承担"hast 树结构闸门"职责——在 ReactMarkdown 渲染前
 *  校验 markdown 是否会触发浏览器 DOM 修复式崩坏。由于 [MarkdownContent]
 *  已切换到自定义 hast 渲染（不再依赖 ReactMarkdown），所有结构问题都
 *  由组件层消化，不再需要预解析闸门。本文件当前仅保留 escapeForPreCodeBlock
 *  作为渲染异常时的兜底（虽然实际极少触发）。
 *
 *  历史说明保留如下，了解设计动机；具体的扫描代码已移除。              */

/* ─────────────────────────────────────────────────────────────────── */
/*  Fallback 清洗：把"渲染异常"或"结构不合法"的 markdown 字符串做     */
/*  ──── 轻量清洗，让它能在 <pre><code> 里完整、原样展示。            */
/* ─────────────────────────────────────────────────────────────────── */

/**
 * 给一段字符串做 escape，让它能在 <pre><code> 里完整、原样展示。具体动作：
 * 1. 把 HTML 特殊字符转义为实体（& < >），避免浏览器把它当 HTML 解析。
 * 2. 对 ``` 和 ~~~ 围栏字符做"半角转全角"处理，避免它们在 <pre> 里被
 *    任何二次 markdown 解析器再次误识别。
 *
 * 注意：此函数不会改写原 markdown 里的换行、缩进、Unicode 字符——目的是
 * "可读地显示原文"而不是"美化输出"。
 */
export function escapeForPreCodeBlock(content: string): string {
  return content
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    // 把围栏符号转成视觉接近的全角字符（仅在 fallback 中使用）
    .replace(/```/g, '＇＇＇')
    .replace(/~~~/g, '～～～');
}
